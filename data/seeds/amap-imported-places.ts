export interface AmapImportedPlace extends MapPoi {
  sourceRow: number
  locationCode: string
  summary: string
  address: string
  sourcePoint: { lng: number, lat: number, crs: 'GCJ-02' | 'WGS84' }
  coordinateSource: string
  verificationStatus: 'owner-map-only'
}

/**
 * Seed coordinates are stored as obfuscated payloads (shared/utils/geo-obfuscation)
 * so the shipped bundle contains no plaintext longitude/latitude literals.
 * The key ships with the bundle: this raises the bar for bulk scrapers, it does
 * not stop a determined reverse-engineer.
 */
const SEED_GEO_KEY = '7a7df79c9590e1638fcc241567d60467798fa8e14f9894f2'

function seedPoint(encoded: string): AmapImportedPlace['sourcePoint'] {
  const decoded = decodePlacePoint(encoded, SEED_GEO_KEY)
  if (!decoded || (decoded.coordinateSystem !== 'WGS84' && decoded.coordinateSystem !== 'GCJ-02')) {
    throw new Error('seed geo payload failed to decode')
  }
  return { lng: decoded.longitude, lat: decoded.latitude, crs: decoded.coordinateSystem }
}
